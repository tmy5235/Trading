import { chromium, expect } from '@playwright/test'
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--no-sandbox']})
const page = await browser.newPage({viewport:{width:1400,height:900}})
try {
  await page.goto('http://127.0.0.1:18862/', {waitUntil:'domcontentloaded'})
  await page.locator('summary').getByText('Inspect recent candles',{exact:true}).click()
  const candle = page.getByRole('group',{name:'Inspect candle'}).getByRole('button',{name:'2026-11-09 14:30:00 UTC'})
  await expect(candle).toBeVisible({timeout:15000})
  await candle.click()
  await expect(page.getByText('Open 13.00, High 15.00, Low 12.00, Close 14.00, Volume 1,200 shares',{exact:false})).toBeVisible()
  await expect(page.locator('.market-panel').getByText('coverage 1/1; Yahoo history',{exact:false})).toBeVisible()
  const toggle=page.getByRole('button',{name:'Show SMA lines'})
  await expect(toggle).toHaveAttribute('aria-pressed','true')
  const chart=page.locator('.chart-canvas')
  await page.mouse.move(0,0)
  const visible=await chart.screenshot()
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed','false')
  await page.mouse.move(0,0)
  const hidden=await chart.screenshot()
  expect(hidden.equals(visible)).toBe(false)
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'Show signals'}).click()
  await expect(page.getByRole('button',{name:'Hide signals'})).toBeVisible()
  await page.getByRole('group',{name:'Timeframe'}).getByRole('button',{name:'5m',exact:true}).click()
  await page.getByRole('group',{name:'Inspect candle'}).getByRole('button',{name:'2026-11-09 14:30:00 UTC'}).click()
  await expect(page.getByText('Yahoo history + stream',{exact:false})).toBeVisible({timeout:15000})
  await page.getByRole('button',{name:'Go to latest'}).click()
  const data = await (await page.request.get('http://127.0.0.1:18861/api/live-history?symbol=AAPL&timeframe=1m')).json()
  const history = data.records.find(x=>x.candle.timestamp === '2026-11-09T14:30:00Z')
  expect(history.candle).toEqual({timestamp:'2026-11-09T14:30:00Z',open:13,high:15,low:12,close:14,volume:1200})
  expect(history.data_source).toBe('Yahoo history')
  console.log('PASS: synthetic historical candle and source match API/UI; SMA visibility changes the chart, signal toggle, timeframe, and latest controls work')
} finally { await browser.close() }
