import { chromium, expect } from '@playwright/test'
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--no-sandbox']})
const page = await browser.newPage({viewport:{width:1400,height:900}})
const api = page.request
try {
  await page.goto('http://127.0.0.1:18862/', {waitUntil:'domcontentloaded'})
  const options = await (await api.get('http://127.0.0.1:18861/api/replay/options')).json()
  const item=options.find(x=>x.symbol==='AAPL')
  expect(item).toBeTruthy()
  const scope=JSON.stringify(['AAPL',item.start,item.end])
  const submission = await api.post('http://127.0.0.1:18861/api/paper/action', {data:{request_id:'snapshot-pending-order',symbol:'AAPL',action:'buy',quantity:1,mode:'replay',scope,cursor:0}})
  expect(submission.ok()).toBe(true)
  expect((await submission.json()).status).toBe('pending')
  const getAccount=async()=> (await api.get('http://127.0.0.1:18861/api/paper/account')).json()
  const before=await getAccount()
  await page.getByRole('group',{name:'Mode'}).getByRole('button',{name:'Snapshot'}).click()
  await expect(page.getByText(/Snapshot as of .* 6 candles · 1m/)).toBeVisible({timeout:15000})
  await expect(page.locator('.chart-canvas canvas').first()).toBeVisible()
  const frame = await page.locator('.chart-canvas').boundingBox()
  const drawing = await page.locator('.chart-canvas canvas').first().boundingBox()
  expect(drawing.x).toBeGreaterThanOrEqual(frame.x - 1)
  expect(drawing.y).toBeGreaterThanOrEqual(frame.y - 1)
  expect(drawing.y + drawing.height).toBeLessThanOrEqual(frame.y + frame.height + 1)
  await expect(page.getByRole('button',{name:'Next observation'})).toHaveCount(0)
  await page.locator('summary').getByText('Trading controls and history',{exact:true}).click()
  await expect(page.getByRole('button',{name:'Buy',exact:true})).toBeDisabled()
  await page.locator('summary').getByText('Inspect recent candles',{exact:true}).click()
  await page.getByRole('group',{name:'Inspect candle'}).getByRole('button',{name:'2026-11-09 14:30:00 UTC'}).click()
  await expect(page.getByText('Open 13.00, High 15.00, Low 12.00, Close 14.00, Volume 1,200 shares',{exact:false})).toBeVisible()
  await page.getByRole('group',{name:'Timeframe'}).getByRole('button',{name:'5m',exact:true}).click()
  await expect(page.getByText(/Snapshot as of .* 2 candles · 5m/)).toBeVisible()
  await expect(page.locator('.chart-canvas canvas').first()).toBeVisible()
  await page.getByRole('group',{name:'Inspect candle'}).getByRole('button',{name:'2026-11-09 14:30:00 UTC'}).click()
  await expect(page.getByText('Open 13.00, High 19.00, Low 7.00, Close 19.00, Volume 2,080 shares',{exact:false})).toBeVisible()
  let after=await getAccount()
  expect(after.cash).toBe(before.cash)
  expect(after.positions).toEqual(before.positions)
  expect(after.orders).toEqual(before.orders)
  await page.getByRole('button',{name:'Step through observations'}).click()
  await expect(page.getByRole('button',{name:'Next observation'})).toBeEnabled()
  await page.getByRole('button',{name:'Back to snapshot'}).click()
  await expect(page.getByText(/Snapshot as of .* 2 candles · 5m/)).toBeVisible()
  await page.getByRole('button',{name:'Change time range'}).click()
  await page.getByLabel('Start UTC:').fill('2026-11-10T14:30:00Z')
  await page.getByLabel('End UTC:').fill('2026-11-10T15:00:00Z')
  await page.getByRole('button',{name:'Load snapshot'}).click()
  await expect(page.getByText('No recorded candles are available for this time range.')).toBeVisible()
  after=await getAccount()
  expect(after.orders).toEqual(before.orders)
  console.log('PASS: automatic snapshot; matching 1m and 5m candles; empty range; optional step mode; pending paper order unchanged')
} finally { await browser.close() }
